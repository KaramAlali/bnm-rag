"""Retrieval on the golden set (plan step 4): for each question with expected chunks, where do
those chunks rank under keyword, vector and hybrid search? Writes evals/retrieval_results.md
(generated; the analysis is in docs/03-retrieval-results.md).

recall@k: the share of a question's `expected` chunks in the top k, averaged over questions.
all@k:    the share of questions with every expected chunk in the top k.
hit@k:    the share of questions with at least one expected chunk in the top k.
Questions with no expected chunks (not_covered) are left out: there is nothing to retrieve.
Filters are deliberately off: applies_to labels answers rather than dropping chunks (PROGRESS,
design note), and draft questions need the exposure draft.

Usage: uv run python -m bnm_rag.index.evaluate
"""

from __future__ import annotations

import datetime as dt
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

from bnm_rag.parse.document import CORPUS, ROOT

GOLDEN = ROOT / "evals" / "golden.yaml"
OUT = ROOT / "evals" / "retrieval_results.md"
KS = (5, 10, 20)
DEPTH = max(KS)

# "Frame" paragraphs say who a document applies to, what its terms mean, when it starts and
# what it replaces. Answers need them, but they rarely share words or meaning with a question
# ("which tech rules apply and when?" vs "This policy document comes into effect on ..."), so
# they are scored apart from the content paragraphs.
FRAME = re.compile(r"^\d+\.?\s+(Applicability|Effective date|Interpretation|"
                   r"Policy documents and circulars superseded)", re.IGNORECASE)


def role(chunk: dict) -> str:
    return "frame" if FRAME.match(chunk.get("section") or "") else "content"


def ranks(expected: list[str], retrieved: list[str]) -> dict[str, int | None]:
    """1-based rank of each expected chunk in `retrieved`, None if absent."""
    pos = {cid: i + 1 for i, cid in reversed(list(enumerate(retrieved)))}
    return {cid: pos.get(cid) for cid in expected}


def scores(found: dict[str, int | None], k: int) -> tuple[float, bool, bool]:
    """(recall@k, all@k, hit@k) for one question."""
    within = [r is not None and r <= k for r in found.values()]
    return sum(within) / len(within), all(within), any(within)


def summarize(rows: list[dict[str, int | None]]) -> dict[int, tuple[float, float, float]]:
    """k → (mean recall@k, all@k rate, hit@k rate) over questions."""
    out = {}
    for k in KS:
        per_q = [scores(r, k) for r in rows]
        n = len(per_q)
        out[k] = tuple(sum(s[i] for s in per_q) / n for i in range(3))
    return out


def load_golden(path: Path = GOLDEN) -> list[dict]:
    with open(path, encoding="utf-8") as f:
        return [q for q in yaml.safe_load(f)["questions"] if q["expected"]]


def run(modes: tuple[str, ...]) -> dict[str, dict[str, dict[str, int | None]]]:
    """mode → question id → expected chunk → rank (top DEPTH)."""
    from bnm_rag.index.azure import search  # Azure only when actually run

    out: dict[str, dict] = defaultdict(dict)
    for q in load_golden():
        for mode in modes:
            got = [c["chunk_id"] for c in search(q["question"], mode=mode, top=DEPTH)]
            out[mode][q["id"]] = ranks(q["expected"], got)
    return out


def _pct(x: float) -> str:
    return f"{x:.0%}"


def by_role(results: dict[str, dict[str, dict]], roles: dict[str, str], k: int = 5
            ) -> dict[str, dict[str, tuple[int, int]]]:
    """mode → role → (expected chunks of that role within the top k, all of that role).
    Counted per expected chunk, not averaged per question."""
    out: dict[str, dict[str, list[int]]] = {}
    for mode, per_q in results.items():
        counts = {"content": [0, 0], "frame": [0, 0]}
        for found in per_q.values():
            for cid, r in found.items():
                c = counts[roles[cid]]
                c[0] += r is not None and r <= k
                c[1] += 1
        out[mode] = {name: tuple(v) for name, v in counts.items()}
    return out


def report(results: dict[str, dict[str, dict]], questions: list[dict],
           roles: dict[str, str]) -> str:
    modes = list(results)
    lines = [
        "# Retrieval results (generated)",
        "",
        f"Generated by `uv run python -m bnm_rag.index.evaluate` on {dt.date.today()}. "
        f"{len(questions)} golden questions with expected chunks; analysis in "
        "`docs/03-retrieval-results.md`.",
        "",
        "## Overall",
        "",
        "| mode | " + " | ".join(f"recall@{k}" for k in KS) + " | all@5 | hit@5 |",
        "|---|" + "---:|" * (len(KS) + 2),
    ]
    for m in modes:
        s = summarize(list(results[m].values()))
        lines.append(f"| {m} | " + " | ".join(_pct(s[k][0]) for k in KS)
                     + f" | {_pct(s[5][1])} | {_pct(s[5][2])} |")

    split = by_role(results, roles)
    lines += ["", "## Content vs frame paragraphs (expected chunks in the top 5)", "",
              "Frame = Applicability, Effective date, Interpretation, Superseded sections.", "",
              "| mode | content | frame |", "|---|---:|---:|"]
    for m in modes:
        cells = [f"{_pct(a / b)} ({a}/{b})" for a, b in (split[m]["content"],
                                                        split[m]["frame"])]
        lines.append(f"| {m} | " + " | ".join(cells) + " |")

    groups: dict[str, list[str]] = defaultdict(list)
    for q in questions:
        groups[f"lang: {q['lang']}"].append(q["id"])
        for t in q["tags"]:
            groups[f"tag: {t}"].append(q["id"])
    lines += ["", "## recall@5 by group", "",
              "| group | n | " + " | ".join(modes) + " |", "|---|---:|" + "---:|" * len(modes)]
    for g in sorted(groups):
        ids = groups[g]
        cells = [_pct(summarize([results[m][i] for i in ids])[5][0]) for m in modes]
        lines.append(f"| {g} | {len(ids)} | " + " | ".join(cells) + " |")

    lines += ["", "## Per question", "",
              f"Rank of each expected chunk (top {DEPTH}; `-` = not retrieved). "
              "**Bold** = outside the top 5.", "",
              "| id | expected | " + " | ".join(modes) + " |", "|---|---|" + "---|" * len(modes)]
    for q in questions:
        for j, cid in enumerate(q["expected"]):
            cells = []
            for m in modes:
                r = results[m][q["id"]][cid]
                cells.append("-" if r is None else (str(r) if r <= 5 else f"**{r}**"))
            qid = q["id"] if j == 0 else ""
            lines.append(f"| {qid} | `{cid}` | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    from bnm_rag.index.azure import MODES

    sys.stdout.reconfigure(encoding="utf-8")
    questions = load_golden()
    with open(CORPUS / "chunks.jsonl", encoding="utf-8") as f:
        roles = {c["chunk_id"]: role(c) for c in map(json.loads, f)}
    results = run(MODES)
    text = report(results, questions, roles)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(text.split("## recall@5 by group")[0])
    print(f"→ {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
